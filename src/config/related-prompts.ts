/** Other prompts in the same topic, at most `RELATED_LIMIT`, catalog order ignored. */
export function curatedRelatedSlugs(slug: string): string[] {
  const found: string[] = [];
  for (const group of RELATED_TOPICS) {
    const index = group.indexOf(slug);
    if (index < 0) continue;
    const ring = [...group.slice(index + 1), ...group.slice(0, index)];
    for (const other of ring) {
      if (other === slug || found.includes(other)) continue;
      found.push(other);
      if (found.length >= RELATED_LIMIT) return found;
    }
  }
  return found;
}
